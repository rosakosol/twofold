-- ---------------------------------------------------------------------------
-- Deliberately not changed
-- ---------------------------------------------------------------------------
--
-- China. Fifteen Xinjiang airports (URC, KHG, HTN, AKU, KRL, ...) are recorded as Asia/Shanghai
-- when they geographically fall in Asia/Urumqi, two hours behind. That is left exactly as it is.
-- China runs one official clock nationwide and airlines schedule, publish and board every domestic
-- flight in Beijing time. "Correcting" these would move a Urumqi departure two hours away from
-- what is printed on the passenger's boarding pass. Geographic correctness and flight correctness
-- are not the same thing here, and this app cares about the second one.
--
-- YEU (Eureka, Nunavut). An 80°N research station with no commercial service, whose zone is
-- genuinely disputed between sources. No flight in this app will ever touch it.
--
-- ~650 rows that differ in name only. Asia/Calcutta rather than Asia/Kolkata, Asia/Rangoon rather
-- than Asia/Yangon, Europe/Kiev rather than Europe/Kyiv, America/Godthab rather than America/Nuuk,
-- America/Buenos_Aires rather than America/Argentina/Buenos_Aires, and so on: deprecated aliases
-- that resolve to the identical zone. Also pairs like America/Anchorage against America/Nome, or
-- America/New_York against America/Detroit — distinct entries that have carried identical rules
-- for decades. Rewriting 650 production rows to change nothing observable is risk without benefit.

-- ---------------------------------------------------------------------------
-- flights: carry the corrections through to rows already saved
-- ---------------------------------------------------------------------------
--
-- Correcting the reference table does not move a flight that already copied a value out of it, and
-- nothing else revisits those rows — the poller only rewrites live-tracking fields. So the
-- corrections are pushed through by hand.
--
-- Matched on the OLD value, not just the airport code. A flight holding the stale string is one
-- that copied it from here; a flight holding anything else got its timezone from AeroAPI directly,
-- which is the live source and is left alone. Anything still null is picked up by the same
-- `airports` join the previous migration used, now that the gaps above are filled.

