-- ---------------------------------------------------------------------------
-- airports: correct the timezones that are wrong, and fill in the ones that are missing
-- ---------------------------------------------------------------------------
--
-- Found while tracking down why UA60 out of SFO displayed at the wrong hour (see
-- 20260928000000_backfill_flight_airport_timezones.sql, which teaches flights to take their
-- timezone from this table). If flights now trust `airports.timezone`, the values in it have to be
-- right, and 616 of them were not.
--
-- Every value below was derived by looking up each airport's own latitude and longitude against the
-- IANA timezone boundary shapefiles, then compared against what the table already held. That
-- comparison flagged 708 rows. Most are harmless and are deliberately NOT touched here — see the
-- bottom of this file. These are the ones that matter.
--
-- ---------------------------------------------------------------------------
-- 1. Victoria and Tasmania are swapped
-- ---------------------------------------------------------------------------
--
-- Every Victorian airport was recorded as Australia/Hobart and every Tasmanian one as
-- Australia/Melbourne — including MEL itself, which is the busiest airport in this app.
--
-- Nothing displays wrong today: the two zones have kept identical offsets and identical DST
-- transitions since 2008. But they were different before that (Tasmania used to start daylight
-- saving in early October, Victoria in late October), they are separate entries precisely because
-- the two states legislate their own DST independently, and either one can diverge again. A stored
-- timezone is not a stored offset; it is a promise about which jurisdiction's future rules to
-- follow, and this promise pointed at the wrong state.

